"""One-off helper used on 12 November 2026: copy the sections of the first version of the report (archive/report_version_1_engineering_log/sections)
into report/technical/ and apply the systematic part of the plain-language overhaul:

  * internal code names / nicknames in running text are replaced by the descriptive model names (code names survive only in file paths,
    in the model-name mapping table and in the file inventory);
  * abbreviations in running text are spelled out (BEV, IDM, PPO, DAgger, HD map, CNN, Wh/km);
  * the phrase 'headline model' becomes 'proposed model';
  * figure environments are replaced by the explained figure blocks (report/figure_blocks/<figure name>.tex);
  * parenthetical lists of code names are removed.

The result is then edited by hand (terminology, reinforcement-learning section, model catalogue, introductions). Nothing here changes a number.
Run from the repository root:   venv\\Scripts\\python.exe report\\transform_sections_to_plain_language.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "archive" / "report_version_1_engineering_log" / "sections"
DST = ROOT / "report" / "technical"
DST.mkdir(exist_ok=True)

CODE_TO_NAME = {
    "ov_split": "proposed model", "base_a": "plain-view model with six vehicle-state inputs", "ov_both": "map-overlay model with six vehicle-state inputs",
    "ov_bev_only": "map-overlay model without vehicle-state inputs", "arch_bev_only": "plain-view model without vehicle-state inputs",
    "arch_scalar_only": "model with vehicle-state inputs only", "repo_bc_sparse": "baseline model trained with traffic",
    "repo_bc_clear": "baseline model trained without traffic", "ctrl_nocaut": "caution-study control model", "caut_a": "caution-study caution-aware model",
    "caut_c0": "caution-aware model with caution set to zero", "caut_auto": "caution-aware model with caution derived from weather",
    "deg_base": "weather-degradation-trained model", "ppo_plain": "reinforcement-learning-fine-tuned model without weather input (attempt 4)",
    "ppo_ada": "attempt-4 model with weather input", "vcam": "image-only model", "safe_teacher": "collision-aware teacher",
    "C2": "run C2", "probe_C": "run Probe C", "C3": "run C3", "pilot_cond": "attempt-2 run",
}
WORDS = [
    (r"\bheadline models\b", "proposed models"), (r"\bheadline model\b", "proposed model"), (r"\bHeadline model\b", "Proposed model"),
    (r"\bHeadline-model\b", "Proposed-model"), (r"\bheadline design\b", "proposed design"), (r"\bheadline input design\b", "proposed input design"),
    (r"\bHEADLINE\b", "PROPOSED"), (r"\bBEV\b", "bird's-eye-view"), (r"\bIDM\b", "intelligent driver model"), (r"\bPPO\b", "proximal policy optimisation"),
    (r"\bDAgger\b", "dataset aggregation"), (r"\bHD map\b", "high-definition map"), (r"\bCNN\b", "convolutional neural network"),
    (r"\bWh/km\b", "watt-hours per kilometre"),
]
PROTECT = re.compile(r"(\\(?:pth|code|url|texttt|path|input|label|ref|cite|resizebox)\{[^}]*\}|\\begin\{lstlisting\}.*?\\end\{lstlisting\}|\\includegraphics\[[^\]]*\]\{[^}]*\}|\\begin\{tikzpicture\}.*?\\end\{tikzpicture\})", re.S)
CODE_PAREN = re.compile(r"\s*\((?:code names? )?(?:\\code\{[A-Za-z0-9_\*]+\}(?:\s*,\s*|\s+and\s+|\s*;\s*|\s+or\s+)?)+\)")
FIG_ENV = re.compile(r"\\begin\{figure\}(?:\[[^\]]*\])?(?:(?!\\end\{figure\}).)*?\\includegraphics\[[^\]]*\]\{figures/([^}]*)\.pdf\}.*?\\end\{figure\}", re.S)


def transform(text: str) -> str:
    text = CODE_PAREN.sub("", text)
    text = FIG_ENV.sub(lambda m: "\\input{figure_blocks/" + m.group(1) + "}", text)
    parts = PROTECT.split(text)
    out = []
    for i, part in enumerate(parts):
        if i % 2 == 1:                      # protected segment
            m = re.fullmatch(r"\\code\{([A-Za-z0-9_\*]+)\}", part)
            out.append(CODE_TO_NAME.get(m.group(1), part) if m else part)
            continue
        for pat, rep in WORDS:
            part = re.sub(pat, rep, part)
        out.append(part)
    return "".join(out)


def main():
    for f in sorted(SRC.glob("*.tex")):
        text = f.read_text(encoding="utf-8")
        if f.name.startswith("appendix_a"):
            continue                          # generated by report/make_file_inventory.py
        (DST / f.name).write_text(transform(text), encoding="utf-8")
        print("transformed", f.name)


if __name__ == "__main__":
    main()
